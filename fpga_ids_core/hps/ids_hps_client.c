/*
 * HPS-side driver and self-test for ids_cnn1d_hps_avmm on the DE1-SoC.
 *
 * The component sits on the full HPS-to-FPGA bridge (base 0xC0000000).
 * Classifying one sample costs 16 posted writes (the last one starts the
 * engine) and RESULT polls; the whole result is in that one 32-bit word.
 *
 * Build on the board:   gcc -O2 -o ids_hps_client ids_hps_client.c
 * Cross-compile:        arm-linux-gnueabihf-gcc -O2 -static -o ids_hps_client ids_hps_client.c
 * Run (as root):        ./ids_hps_client [-o <offset hex>] [-b] [-n <loops>]
 *   -o  component offset on the bridge (Platform Designer base address), default 0
 *   -b  release the HPS-to-FPGA bridge from reset if Linux left it there
 *   -n  repeat the 100-sample self-test this many times (default 1)
 */
#include <fcntl.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>
#include <time.h>
#include <unistd.h>

/* 100 labeled CIC-IDS2017 samples plus golden class and logits, generated by
 * rtl/scripts/gen_rtl_data.py. Copy it next to this file when building on the board. */
#include "ids_samples.h"

#define H2F_BRIDGE_BASE   0xC0000000u
#define MAP_SPAN          0x1000u

#define FPGAMGR_STAT      0xFF706000u   /* [2:0] mode, 4 = user mode */
#define RSTMGR_BRGMODRST  0xFFD0501Cu   /* bit0 hps2fpga bridge in reset */
#define L3_REMAP          0xFF800000u   /* write-only */

/* Word offsets, see ids_cnn1d_hps_avmm.sv */
#define REG_RESULT  0
#define REG_CTRL    1
#define REG_IRQ     2
#define REG_ID      3
#define REG_LOGIT   8
#define REG_FEAT    16

#define IDS_ID      0x1D5C0002u

#define RES_CLASS(r)   ((r) & 7u)
#define RES_ATTACK(r)  (((r) >> 3) & 1u)
#define RES_SEQ(r)     ((r) >> 16)

#define CTRL_START     (1u << 0)
#define CTRL_AUTOSTART (1u << 1)

static volatile uint32_t *regs;

static volatile uint32_t *map_phys(int fd, uint32_t addr)
{
    uint32_t page = addr & ~(MAP_SPAN - 1);
    void *p = mmap(NULL, MAP_SPAN, PROT_READ | PROT_WRITE, MAP_SHARED, fd, page);
    if (p == MAP_FAILED) { perror("mmap"); exit(1); }
    return (volatile uint32_t *)((uint8_t *)p + (addr - page));
}

/*
 * Classify one sample (64 int8 features, ap_fixed<8,4> codes = value x 16).
 * Returns the class 0..7 (0 = BENIGN), or -1 on timeout. logits may be NULL.
 */
static int ids_classify(const int8_t x[64], int32_t logits[8])
{
    uint32_t seq = RES_SEQ(regs[REG_RESULT]);
    uint32_t words[16], r;

    memcpy(words, x, 64);                 /* little-endian: feature 4w in bits [7:0] */
    for (int w = 0; w < 16; w++)
        regs[REG_FEAT + w] = words[w];    /* writing FEAT[15] starts the engine */

    for (int spin = 0; ; spin++) {
        r = regs[REG_RESULT];
        if (RES_SEQ(r) != seq)
            break;
        if (spin > 100000)
            return -1;
    }
    if (logits)
        for (int k = 0; k < 8; k++)
            logits[k] = (int32_t)regs[REG_LOGIT + k];
    return (int)RES_CLASS(r);
}

int main(int argc, char **argv)
{
    uint32_t offset = 0;
    int enable_bridge = 0, loops = 1, opt;

    while ((opt = getopt(argc, argv, "o:bn:")) != -1) {
        switch (opt) {
        case 'o': offset = (uint32_t)strtoul(optarg, NULL, 16); break;
        case 'b': enable_bridge = 1; break;
        case 'n': loops = atoi(optarg); break;
        default:
            fprintf(stderr, "usage: %s [-o offset_hex] [-b] [-n loops]\n", argv[0]);
            return 2;
        }
    }

    int fd = open("/dev/mem", O_RDWR | O_SYNC);
    if (fd < 0) { perror("open /dev/mem (run as root)"); return 1; }

    /* Touching the bridge with the FPGA unconfigured or the bridge in reset
     * hangs or faults the CPU, so check both first. */
    volatile uint32_t *fpgamgr = map_phys(fd, FPGAMGR_STAT);
    if ((*fpgamgr & 7u) != 4u) {
        fprintf(stderr, "FPGA is not in user mode (fpgamgr stat 0x%x): load the .rbf/.sof first\n",
                *fpgamgr);
        return 1;
    }
    volatile uint32_t *brgmodrst = map_phys(fd, RSTMGR_BRGMODRST);
    if (*brgmodrst & 1u) {
        if (!enable_bridge) {
            fprintf(stderr, "HPS-to-FPGA bridge is in reset. Enable it with\n"
                            "  echo 1 > /sys/class/fpga_bridge/br0/enable   (if your kernel has it)\n"
                            "or rerun with -b.\n");
            return 1;
        }
        *brgmodrst &= ~1u;                    /* release hps2fpga */
        *map_phys(fd, L3_REMAP) = 0x19;       /* make the bridges visible, as U-Boot does */
    }

    regs = map_phys(fd, H2F_BRIDGE_BASE + offset);
    if (regs[REG_ID] != IDS_ID) {
        fprintf(stderr, "ID reads 0x%08x, expected 0x%08x: wrong offset or wrong FPGA image\n",
                regs[REG_ID], IDS_ID);
        return 1;
    }
    regs[REG_CTRL] = CTRL_AUTOSTART;

    int correct = 0, mismatch = 0, total = 0;
    struct timespec t0, t1;
    clock_gettime(CLOCK_MONOTONIC, &t0);
    for (int l = 0; l < loops; l++) {
        for (int s = 0; s < IDS_N_SAMPLES; s++) {
            int32_t lg[8];
            int cls = ids_classify((const int8_t *)IDS_X[s], lg);
            int bad = cls != IDS_GOLDEN[s];
            for (int k = 0; k < 8; k++)
                bad |= lg[k] != IDS_GOLDEN_LOGIT[s][k];
            mismatch += bad;
            correct += cls == IDS_LABEL[s];
            total++;
        }
    }
    clock_gettime(CLOCK_MONOTONIC, &t1);
    double us = ((t1.tv_sec - t0.tv_sec) * 1e9 + (t1.tv_nsec - t0.tv_nsec)) / 1e3;

    /* Class only (no logit reads): the fast path an IDS would use */
    clock_gettime(CLOCK_MONOTONIC, &t0);
    for (int s = 0; s < IDS_N_SAMPLES; s++)
        ids_classify((const int8_t *)IDS_X[s], NULL);
    clock_gettime(CLOCK_MONOTONIC, &t1);
    double us_fast = ((t1.tv_sec - t0.tv_sec) * 1e9 + (t1.tv_nsec - t0.tv_nsec)) / 1e3;

    /* Cost of one bridge read */
    uint32_t sink = 0;
    clock_gettime(CLOCK_MONOTONIC, &t0);
    for (int i = 0; i < 10000; i++)
        sink += regs[REG_RESULT];
    clock_gettime(CLOCK_MONOTONIC, &t1);
    double ns_read = ((t1.tv_sec - t0.tv_sec) * 1e9 + (t1.tv_nsec - t0.tv_nsec)) / 1e4;
    (void)sink;

    printf("Samples:                 %d\n", total);
    printf("Accuracy vs labels:      %.2f%%\n", 100.0 * correct / total);
    printf("Golden mismatches:       %d (expect 0)\n", mismatch);
    printf("Time / sample + logits:  %.2f us\n", us / total);
    printf("Time / sample, class:    %.2f us\n", us_fast / IDS_N_SAMPLES);
    printf("One RESULT read:         %.0f ns\n", ns_read);
    printf("FPGA SEQ counter:        %u\n", RES_SEQ(regs[REG_RESULT]));
    return mismatch != 0;
}
